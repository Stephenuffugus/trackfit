/** Read the canonical premium state. Always returns a valid object —
 *  corrupt or missing storage maps to the default zero state. */
export function loadPremium(): PremiumState {
  return safeRead();
}

/** Pure check — does the user currently have premium access? Reads
 *  storage by default; pass an already-loaded state if you have one
 *  to avoid a redundant localStorage hit. */
export function isPremium(state?: PremiumState): boolean {
  const s = state ?? safeRead();
  return s.active === true && s.source !== "none";
}

/**
 * Hash a typed license code and check it against the embedded
 * allowlist. Returns the hash on success (so the caller can persist
 * it via `activate()`) or `null` on rejection.
 *
 * Async because `crypto.subtle.digest` is async. The Promise resolves
 * within a few milliseconds in practice — there's no reason to add
 * spinner UI for it.
 */
export async function validateLicense(code: string): Promise<string | null> {
  const normalised = normaliseCode(code);
  if (normalised.length === 0) return null;
  let hash: string;
  try {
    hash = await sha256Hex(normalised);
  } catch {
    return null;
  }
  return VALID_LICENSE_HASHES.has(hash) ? hash : null;
}

/**
 * Persist a verified license. Defence in depth: even though the caller
 * (`LicenseActivation`) only calls us with hashes that came back from
 * `validateLicense`, we re-check the allowlist here so a buggy caller
 * can never accidentally activate premium with garbage. The thrown
 * error surfaces as a generic "couldn't activate" toast — the user
 * sees the same message as a typo'd code.
 */
export function activate(hash: string): void {
  if (!VALID_LICENSE_HASHES.has(hash)) {
    throw new Error("Trackfit: refusing to activate with unknown license hash.");
  }
  // Preserve the existing photo_id_used counter on activation. Premium
  // users don't care about the quota anymore (it's bypassed), but if
  // they ever deactivate we want their previous usage to stick — the
  // alternative would let someone burn through three trials, activate,
  // deactivate, and get three more.
  const prev = safeRead();
  const next: PremiumState = {
    active: true,
    source: "license",
    license_hash: hash,
    activated_at: new Date().toISOString(),
    photo_id_used: prev.photo_id_used,
  };
  safeWrite(next);
}

/**
 * Remove premium activation entirely. Wipes the license hash and the
 * activated_at timestamp, but PRESERVES the photo_id_used counter so
 * that a deactivated user can't reset their free trials by toggling.
 */
export function deactivate(): void {
  const prev = safeRead();
  const next: PremiumState = {
    active: false,
    source: "none",
    photo_id_used: prev.photo_id_used,
  };
  safeWrite(next);
}

/**
 * Atomically consume one photo-ID quota slot. For non-premium users
 * this reads the current count, increments it if there's room, writes
 * back, and returns whether the call is allowed plus how many remain.
 * For premium users it returns `{ allowed: true, remaining: Infinity,
 * total: Infinity }` without touching storage — premium is unlimited.
 *
 * "Atomic" here means "atomic enough for localStorage on a single
 * device" — there's a theoretical race if two tabs hammer photo-ID
 * simultaneously, but the worst case is the user gets four trials
 * instead of three, which is harmless.
 */
export function consumePhotoIdQuota(): {
  allowed: boolean;
  remaining: number;
  total: number;
} {
  const state = safeRead();
  if (isPremium(state)) {
    return { allowed: true, remaining: Infinity, total: Infinity };
  }
  if (state.photo_id_used >= FREE_PHOTO_ID_QUOTA) {
    return {
      allowed: false,
      remaining: 0,
      total: FREE_PHOTO_ID_QUOTA,
    };
  }
  const nextUsed = state.photo_id_used + 1;
  safeWrite({ ...state, photo_id_used: nextUsed });
  return {
    allowed: true,
    remaining: FREE_PHOTO_ID_QUOTA - nextUsed,
    total: FREE_PHOTO_ID_QUOTA,
  };
}

/** Read remaining quota without consuming. Premium → Infinity. */
export function getPhotoIdQuotaRemaining(): number {
  const state = safeRead();
  if (isPremium(state)) return Infinity;
  return Math.max(0, FREE_PHOTO_ID_QUOTA - state.photo_id_used);
}

