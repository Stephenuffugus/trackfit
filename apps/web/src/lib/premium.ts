/* ------------------------------------------------------------------ */
/* Internal helpers                                                   */
/* ------------------------------------------------------------------ */

const DEFAULT_STATE: PremiumState = {
  active: false,
  source: "none",
  photo_id_used: 0,
};

/**
 * localStorage can throw in private-mode Safari, locked-down corporate
 * devices, or quota-exceeded scenarios. Every access goes through these
 * helpers so callers don't have to think about it — failure mode is
 * "act as if no state was stored", which is the right default.
 */
function safeRead(): PremiumState {
  try {
    const raw = localStorage.getItem(PREMIUM_STORAGE_KEY);
    if (!raw) return { ...DEFAULT_STATE };
    const parsed = JSON.parse(raw);
    if (!parsed || typeof parsed !== "object") return { ...DEFAULT_STATE };
    // Shape-guard each field. A hand-edited or partially-written blob
    // shouldn't poison the rest of the app.
    const active = parsed.active === true;
    const source: PremiumState["source"] =
      parsed.source === "license" || parsed.source === "trial"
        ? parsed.source
        : "none";
    const license_hash =
      typeof parsed.license_hash === "string" ? parsed.license_hash : undefined;
    const activated_at =
      typeof parsed.activated_at === "string" ? parsed.activated_at : undefined;
    const photo_id_used =
      typeof parsed.photo_id_used === "number" &&
      Number.isFinite(parsed.photo_id_used) &&
      parsed.photo_id_used >= 0
        ? Math.floor(parsed.photo_id_used)
        : 0;
    return { active, source, license_hash, activated_at, photo_id_used };
  } catch {
    return { ...DEFAULT_STATE };
  }
}

function safeWrite(state: PremiumState): void {
  try {
    localStorage.setItem(PREMIUM_STORAGE_KEY, JSON.stringify(state));
  } catch {
    /* private mode / quota — silent failure is correct here, the app
     * keeps working and the user can re-activate next session if it
     * really matters. */
  }
}

/** Hex-encode a Uint8Array. `crypto.subtle.digest` returns an
 *  ArrayBuffer so we copy into a Uint8Array first. */
function bytesToHex(bytes: Uint8Array): string {
  const out = new Array<string>(bytes.length);
  for (let i = 0; i < bytes.length; i += 1) {
    out[i] = bytes[i]!.toString(16).padStart(2, "0");
  }
  return out.join("");
}

async function sha256Hex(input: string): Promise<string> {
  // crypto.subtle.digest exists in browsers and in Node 18+ — both
  // targets we care about. If somehow it's missing (very old browser,
  // ancient JSDOM) we surface a clear error rather than silently
  // returning a junk hash.
  const subtle =
    typeof crypto !== "undefined" && crypto.subtle ? crypto.subtle : null;
  if (!subtle) {
    throw new Error(
      "Trackfit: crypto.subtle is not available in this environment.",
    );
  }
  const buf = await subtle.digest("SHA-256", new TextEncoder().encode(input));
  return bytesToHex(new Uint8Array(buf));
}

/**
 * Normalise a typed license code: trim, strip whitespace, uppercase.
 * Stephen's codes are issued in `TFP-XXXX-XXXX-XXXX` form — the dashes
 * are PRESERVED (they're part of what we hash) but case and stray
 * spaces from autocorrect are not. So `tfp-aaaa-bbbb-cccc` and
 * `  TFP-AAAA-BBBB-CCCC  ` produce the same hash.
 */
function normaliseCode(code: string): string {
  return code.replace(/\s+/g, "").toUpperCase();
}

