/**
 * Single source of truth for Trackfit Premium activation state.
 *
 * The freemium model: the gap solver, all 16 track libraries, manual
 * inventory (no cap), the layout suggester, the reference-object gap
 * measurement, the manual photo capture, the 1:1 cut-template PDF, JSON
 * export/import, and the comfort prefs are all FREE FOREVER. Premium
 * unlocks photo-ID auto-fill (with three free lifetime trials so the user
 * can taste the magic), the insurance-grade inventory PDF report, and the
 * full eight-vendor marketplace link list. (Free users get the top two
 * vendors.) The list of premium features is intentionally narrow — the
 * free tier MUST stay legitimately useful per Stephen's instructions.
 *
 * Activation flow: Stephen issues `TFP-XXXX-XXXX-XXXX` codes manually
 * after a Stripe Checkout completes. (At <50 customers, manual is the
 * right call — we're not Adobe.) He runs a small CLI to generate
 * (code, hash) pairs and pastes the hash into the embedded allowlist
 * below. The user types the code into the activation modal; we hash it
 * with SHA-256 and check the hash against the allowlist. Hash-only
 * protection means inspecting the bundled JS doesn't reveal valid
 * codes — only their hashes — so a casual reader can't generate codes
 * for free.
 *
 * Persistence: the activated state lives in localStorage. v1 lets a
 * single license activate on as many devices as the user wants — that's
 * a deliberate trade-off; honest users own multiple devices, and
 * dishonest users will share the code with three friends regardless of
 * what we do. We're not in the DRM business.
 *
 * The photo-ID quota is *lifetime* (not per-session), tracked in the
 * same localStorage blob. Three is enough for the user to feel the
 * magic on their first batch of photos and then hit the gate, which
 * gives us a clean validation signal: did they click "Upgrade"?
 */

/* ------------------------------------------------------------------ */
/* Public types & constants                                           */
/* ------------------------------------------------------------------ */

export interface PremiumState {
  /** True iff the user has a verified license activated. */
  active: boolean;
  /** How premium was granted. "trial" is reserved for a future
   *  promo flow; today we only emit "license" or "none". */
  source: "license" | "trial" | "none";
  /** The SHA-256 hex of the verified code. We store the HASH, not the
   *  code itself — anyone with localStorage read access (e.g. a
   *  shared computer) shouldn't be able to harvest the code. */
  license_hash?: string;
  /** ISO timestamp of when activation happened. Surfaced in the
   *  Settings panel ("Premium ✦ active since 2026-05-05"). */
  activated_at?: string;
  /** Lifetime count of photo-ID auto-fill calls made by this device.
   *  Premium users still increment this counter (it's a no-op for them
   *  since the gate is bypassed) so the schema is stable across
   *  upgrade/downgrade. */
  photo_id_used: number;
}

/** Number of free photo-ID calls a non-premium device gets. Lifetime,
 *  not per-session — three feels generous enough to taste the magic
 *  without losing the validation signal. */
export const FREE_PHOTO_ID_QUOTA = 3;

/** How many marketplace vendors free users see in the suggester /
 *  near-miss panels. Premium unlocks the rest of the eight-vendor list. */
export const FREE_MARKETPLACE_VENDOR_COUNT = 2;

/** localStorage key. Versioned so a future schema change can be additive. */
export const PREMIUM_STORAGE_KEY = "trackfit.premium.v1";

